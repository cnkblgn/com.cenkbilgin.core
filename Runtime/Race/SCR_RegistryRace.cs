using System;
using System.Collections.Generic;
using UnityEngine;
using Core;

namespace Core.Race
{
    [CreateAssetMenu(fileName = "SCO_RaceRegistry", menuName = "Resources/Core/Race Registry", order = -6)]
    public sealed class RegistryRace : Registry
    {
        public override int Priority => -6;

        [Header("_")]
        [SerializeField, Required] private string[] tags;

        [Header("_")]
        [SerializeField] private RaceEntry[] entries;

        [Header("_")]
        [SerializeField, Required] private string idPath = "Assets/Scripts/SCR_GeneratedRaceIDs.cs";
        [SerializeField, Required] private string tagPath = "Assets/Scripts/SCR_GeneratedRaceTags.cs";

        private readonly Dictionary<string, RaceEntry> extraEntries = new();
        private readonly HashSet<string> extraTags = new();

        public override void OnAfterAssembliesLoaded() => BuildDatabase();
        public override void OnAfterScriptLoad() => BuildDatabase();
        public void BuildDatabase() => RaceDatabase.Build(CoreUtility.MergeEntries(entries, extraEntries, static entry => entry.ID.Key), CoreUtility.MergeEntries(tags, extraTags));
        public void AppendEntries(IReadOnlyList<RaceEntry> entries) => CoreUtility.AppendEntries(entries, extraEntries, static entry => entry.ID.Key, static entry => !string.IsNullOrWhiteSpace(entry.ID.Key));
        public void AppendTags(IReadOnlyList<string> tags) => CoreUtility.AppendUnique(tags, extraTags, StringComparer.Ordinal);


#if UNITY_EDITOR
        protected override void OnValidate()
        {
            base.OnValidate();

            for (int i = 0; i < entries.Length; i++)
            {
                entries[i].OnValidate();
            }
        }

        public override void Reload()
        {
            BuildDatabase();
            GenerateTags();
            GenerateIDs();
        }

        private void GenerateTags()
        {
            Core.Editor.SourceGenerator generator = new();

            generator.AutoGenerated();

            generator.Using("System");
            generator.Line();

            using (generator.Namespace("Core.Race"))
            using (generator.Class("public static class RaceTags"))
            {
                foreach (RaceTag tag in RaceDatabase.GetTags())
                {
                    generator.Field($"public static readonly RaceTag {tag.Key.ToIdentifier()} = new({tag.Key.ToLiteral()},{tag.Index})");
                }
            }

            Core.Editor.EditorUtility.GenerateTextFile(tagPath, generator.ToString());
        }
        private void GenerateIDs()
        {
            Core.Editor.SourceGenerator generator = new();

            generator.AutoGenerated();

            generator.Using("System");
            generator.Line();

            using (generator.Namespace("Core.Race"))
            using (generator.Class("public static class RaceIDs"))
            {
                foreach (RaceDefinition definition in RaceDatabase.GetDefinitions())
                {
                    RaceID id = definition.ID;

                    generator.Field($"public static readonly RaceID {id.Key.ToIdentifier()} = new({id.Key.ToLiteral()},{id.Index})");
                }
            }

            Core.Editor.EditorUtility.GenerateTextFile(idPath, generator.ToString());
        }
#endif
    }
}

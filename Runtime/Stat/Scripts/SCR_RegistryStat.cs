using System.Collections.Generic;
using UnityEngine;

namespace Core.Stat
{
    [CreateAssetMenu(fileName = "SCO_StatRegistry", menuName = "Resources/Core/Stat Registry", order = 10)]
    public sealed class RegistryStat : Registry
    {
        public override int Priority => -5;

        [Header("_")]
        [SerializeField] private StatEntry[] entries;

        [Header("_")]
        [SerializeField, Required] private string idPath = "Assets/Scripts/SCR_GeneratedStatIDs.cs";

        private readonly Dictionary<string, StatEntry> extraEntries = new();

        public override void OnAfterAssembliesLoaded() => BuildDatabase();
        public override void OnAfterScriptLoad() => BuildDatabase();
        public void BuildDatabase() => StatDatabase.Build(CoreUtility.MergeEntries(entries, extraEntries, static entry => entry.ID.Key));
        public void AppendEntries(IReadOnlyList<StatEntry> entries) => CoreUtility.AppendEntries(entries, extraEntries, static entry => entry.ID.Key, static entry => entry.ID.IsValid);

#if UNITY_EDITOR
        protected override void OnValidate()
        {
            base.OnValidate();

            for (int i = 0; i < entries.Length; i++) entries[i].Name = entries[i].ID.Key;
        }

        public override void Reload()
        {
            BuildDatabase();

            GenerateIDs();
        }

        private void GenerateIDs()
        {
            Editor.SourceGenerator generator = new();

            generator.AutoGenerated();

            generator.Using("System");
            generator.Line();

            using (generator.Namespace("Core.Stat"))
            using (generator.Class("public static class StatIDs"))
            {
                foreach (StatDefinition definition in StatDatabase.GetDefinitions())
                {
                    string id = definition.ID.Key;
                    int index = definition.ID.Index;

                    generator.Field($"public static readonly StatID {id.ToIdentifier()} = new({id.ToLiteral()},{index})");
                }
            }

            Editor.EditorUtility.GenerateTextFile(idPath, generator.ToString());
        }
#endif
    }
}

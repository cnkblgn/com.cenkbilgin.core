using System.Collections.Generic;
using UnityEngine;

namespace Core.Scenario
{
    [CreateAssetMenu(fileName = "SCO_ScenarioRegistry", menuName = "Resources/Core/Scenario Registry", order = -5)]
    public sealed class RegistryScenario : Registry
    {
        public override int Priority => -5;

        [Header("_")]
        [SerializeField] private ScenarioEntry[] entries;

        [Header("_")]
        [SerializeField, Required] private string idPath = "Assets/Scripts/SCR_GeneratedScenarioIDs.cs";

        private readonly Dictionary<string, ScenarioEntry> extraEntries = new();

        public override void OnAfterAssembliesLoaded() => BuildDatabase();
        public override void OnAfterScriptLoad() => BuildDatabase();
        public void BuildDatabase() => ScenarioDatabase.Build(CoreUtility.MergeEntries(entries, extraEntries, static entry => entry.ID.Key));
        public void AppendEntries(IReadOnlyList<ScenarioEntry> entries) => CoreUtility.AppendEntries(entries, extraEntries, static entry => entry.ID.Key, static entry => !string.IsNullOrWhiteSpace(entry.ID.Key));


#if UNITY_EDITOR
        protected override void OnValidate()
        {
            base.OnValidate();

            for (int i = 0; i < entries.Length; i++)
            {
                entries[i].OnValidate();
            }
        }
        public override void Reload()
        {
            BuildDatabase();
            GenerateIDs();
        }
        private void GenerateIDs()
        {
            Core.Editor.SourceGenerator generator = new();

            generator.AutoGenerated();

            generator.Using("System");
            generator.Line();

            using (generator.Namespace("Core.Scenario"))
            using (generator.Class("public static class ScenarioIDs"))
            {
                foreach (ScenarioDefinition definition in ScenarioDatabase.GetDefinitions())
                {
                    ScenarioID id = definition.ID;

                    generator.Field($"public static readonly ScenarioID {id.Key.ToIdentifier()} = new({id.Key.ToLiteral()},{id.Index})");
                }
            }

            Core.Editor.EditorUtility.GenerateTextFile(idPath, generator.ToString());
        }
#endif
    }
}
